/* Default font */
static const font_t default_font = {
    .data = font_8x8,
    .char_width = 8,
    .char_height = 8,
    .first_char = 32,
    .last_char = 127,
    .bytes_per_char = 8
};

static const font_t* current_font = &default_font;

/*
 * Set current font
 */
void font_set(const font_t* font) {
    if (font) {
        current_font = font;
    } else {
        current_font = &default_font;
    }
}

/*
 * Get current font
 */
const font_t* font_get(void) {
    return current_font;
}

/*
 * Get default font
 */
const font_t* font_get_default(void) {
    return &default_font;
}

/*
 * Draw a single character
 * Returns width of character drawn
 */
int font_draw_char(int x, int y, char c, int color) {
    if (c < current_font->first_char || c > current_font->last_char) {
        return current_font->char_width;
    }

    int idx = c - current_font->first_char;
    const u8* glyph = &current_font->data[idx * current_font->bytes_per_char];

    for (int row = 0; row < current_font->char_height; row++) {
        u8 line = glyph[row];
        for (int col = 0; col < current_font->char_width; col++) {
            if (line & (0x80 >> col)) {
                fb_set_pixel(x + col, y + row, color ? 0 : 1);
            }
        }
    }

    return current_font->char_width;
}

/*
 * Draw string
 * Returns total width drawn
 */
int font_draw_string(int x, int y, const char* str, int color) {
    int start_x = x;

    while (*str) {
        if (*str == '\n') {
            x = start_x;
            y += current_font->char_height + 1;
        } else {
            x += font_draw_char(x, y, *str, color);
        }
        str++;
    }

    return x - start_x;
}

/*
 * Draw string with background
 */
int font_draw_string_bg(int x, int y, const char* str, int fg, int bg) {
    /* Draw background */
    int w = strlen(str) * current_font->char_width;
    fb_fill_rect(x, y, w, current_font->char_height, bg ? 1 : 0);

    /* Draw text */
    return font_draw_string(x, y, str, fg);
}

/*
 * Get string width in pixels
 */
int font_string_width(const char* str) {
    int width = 0;
    while (*str) {
        if (*str != '\n') {
            width += current_font->char_width;
        }
        str++;
    }
    return width;
}

/*
 * Get font height
 */
int font_get_height(void) {
    return current_font->char_height;
}

/*
 * Get font width
 */
int font_get_width(void) {
    return current_font->char_width;
}
