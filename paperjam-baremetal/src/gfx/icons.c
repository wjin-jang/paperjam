/*
 * Get icon bitmap data
 */
const u8* icon_get_data(icon_id_t icon) {
    if (icon >= ICON_COUNT) return NULL;
    return icon_table[icon];
}

/*
 * Draw an icon at specified position
 */
void icon_draw(int x, int y, icon_id_t icon, int color) {
    const u8* data = icon_get_data(icon);
    if (!data) return;

    for (int row = 0; row < ICON_SIZE; row++) {
        u8 byte1 = data[row * 2];
        u8 byte2 = data[row * 2 + 1];

        for (int col = 0; col < 8; col++) {
            if (byte1 & (0x80 >> col)) {
                fb_set_pixel(x + col, y + row, color ? 0 : 1);
            }
        }
        for (int col = 0; col < 8; col++) {
            if (byte2 & (0x80 >> col)) {
                fb_set_pixel(x + 8 + col, y + row, color ? 0 : 1);
            }
        }
    }
}

/*
 * Draw an icon centered in a region
 */
void icon_draw_centered(int x, int y, int w, int h, icon_id_t icon, int color) {
    int ix = x + (w - ICON_SIZE) / 2;
    int iy = y + (h - ICON_SIZE) / 2;
    icon_draw(ix, iy, icon, color);
}
